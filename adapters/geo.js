// «Зууч» — зарын чөлөөт текстээс (гарчиг) байршил/талбай/өрөө таних туслах
// Зөвхөн хоёрдмол утгагүй тэмдэглэгээ: дүүргийн товчлол/нэр, тодорхой хороолол/хотхон. Олдохгүй бол null → шүүлтүүр «байршил тодорхойгүй» гэж татгалзана.
const UB = ['Сүхбаатар', 'Хан-Уул', 'Баянгол', 'Баянзүрх', 'Чингэлтэй', 'Сонгинохайрхан', 'Налайх', 'Багануур', 'Багахангай'];

// Дүүргийн товчлол ба нэр (зарын гарчигт хамгийн түгээмэл: «ХУД, …», «СБД 1-р хороо»)
const ABBR = [
  [/(^|[^А-ЯӨҮЁа-яөүё])ХУД([^А-ЯӨҮЁа-яөүё]|$)|хан[\s-]?уул/i, 'Хан-Уул'],
  [/(^|[^А-ЯӨҮЁа-яөүё])СБД([^А-ЯӨҮЁа-яөүё]|$)|сүхбаатар дүүрэг/i, 'Сүхбаатар'],
  [/(^|[^А-ЯӨҮЁа-яөүё])БЗД([^А-ЯӨҮЁа-яөүё]|$)|баянзүрх/i, 'Баянзүрх'],
  [/(^|[^А-ЯӨҮЁа-яөүё])БГД([^А-ЯӨҮЁа-яөүё]|$)|баянгол/i, 'Баянгол'],
  [/(^|[^А-ЯӨҮЁа-яөүё])СХД([^А-ЯӨҮЁа-яөүё]|$)|сонгинохайрхан/i, 'Сонгинохайрхан'],
  [/(^|[^А-ЯӨҮЁа-яөүё])ЧД([^А-ЯӨҮЁа-яөүё]|$)|чингэлтэй/i, 'Чингэлтэй'],
  [/налайх/i, 'Налайх'],
  [/багануур/i, 'Багануур'],
  [/багахангай/i, 'Багахангай'],
];
// Тодорхой хороолол/газрын нэр → дүүрэг (хоёр дүүргийн заагт орших нэрсийг оруулаагүй)
const PLACES = [
  [/яармаг|зайсан|нисэх|хүннү\s?2222|буянт[\s-]?ухаа|(^|\D)19[\s-]?(р|-р)?\s?хороолол|рапид|viva city|вива сити/i, 'Хан-Уул'],
  [/(^|\D)(3|4|10)[\s-]?(р|-р)?\s?хороолол|ард кино|3[,.]\s?4[\s-]?(р|-р)?\s?хороолол/i, 'Баянгол'],
  [/(^|\D)(13|15)[\s-]?(р|-р)?\s?хороолол|сансар|амгалан|шархад|жуков|улиастай/i, 'Баянзүрх'],
  [/(^|\D)100\s?айл|дамбадаржаа|их сургуулийн гудамж|багшийн дээд/i, 'Сүхбаатар'],
  [/гандан|хайлааст|дэнжийн мянга/i, 'Чингэлтэй'],
  [/толгойт|баянхошуу|(^|\D)21[\s-]?(р|-р)?\s?хороолол|бэлх|сонсголон/i, 'Сонгинохайрхан'],
];
function districtOf(text) {
  const t = String(text || '');
  for (const [rx, d] of ABBR) if (rx.test(t)) return d;
  for (const [rx, d] of PLACES) if (rx.test(t)) return d;
  return null;
}
// omch/URL slug → дүүрэг
const SLUG = { 'sukhbaatar': 'Сүхбаатар', 'khan-uul': 'Хан-Уул', 'bayangol': 'Баянгол', 'bayanzurkh': 'Баянзүрх', 'chingeltei': 'Чингэлтэй', 'songinokhairkhan': 'Сонгинохайрхан', 'nalaikh': 'Налайх', 'baganuur': 'Багануур', 'bagakhangai': 'Багахангай' };
function districtFromSlug(slug) { const s = String(slug || '').toLowerCase().replace(/^ub-/, ''); return SLUG[s] || null; }
// «Баянзүрх дүүрэг» → «Баянзүрх»
function districtFromName(name) { const n = String(name || '').replace(/\s*дүүрэг\s*$/i, '').trim(); return UB.find((d) => d.toLowerCase() === n.toLowerCase()) || null; }

// Талбай (м²): «72мкв», «50.4 м2», «88 м²», «120 кв»
function areaOf(text) {
  const m = String(text || '').match(/(\d{2,4}(?:[.,]\d{1,2})?)\s*(?:мкв|м\.?\s?кв|м2|м²|mkv|кв\.?м|кв(?![а-яөү]))/i);
  if (!m) return null; const v = parseFloat(m[1].replace(',', '.'));
  return v >= 10 && v <= 5000 ? v : null;
}
// Өрөө: «3 өрөө», «2өрөө»
const ROOM_WORDS = { 'нэг': 1, 'хоёр': 2, 'гурван': 3, 'гурав': 3, 'дөрвөн': 4, 'дөрөв': 4, 'таван': 5, 'тав': 5 };
function roomsOf(text) {
  const t = String(text || '');
  const m = t.match(/(^|\D)([1-6])\s?-?\s?өрөө/i); if (m) return Number(m[2]);
  const w = t.toLowerCase().match(/(^|[^а-яөүё])(нэг|хоёр|гурван|гурав|дөрвөн|дөрөв|таван|тав)\s+өрөө/); return w ? ROOM_WORDS[w[2]] : null;
}
// Хэлцэл: түрээс эсэх
const isRent = (text) => /түрээс|түрээслүүл|түрээслэнэ|tures|turees/i.test(String(text || ''));

module.exports = { UB, districtOf, districtFromSlug, districtFromName, areaOf, roomsOf, isRent };
